namespace AssistQuestEditor.Domain;

/// <summary>
/// БЖУ предмета — БЕЛКИ, ЖИРЫ, УГЛЕВОДЫ на порцию (задано автором: «зафиксировать
/// для всех предметов БЖУ для будущих механик»).
///
/// ПОЧЕМУ НА ПОРЦИЮ, А НЕ НА 100 Г. Источники публикуют БЖУ на 100 г, но игрок
/// ест ПОРЦИЮ, а не сто граммов, и шкалы восполняются порцией. Каталог хранит
/// БЖУ на порцию: иначе каждая будущая механика («белка не хватает») начинала бы
/// с умножения на массу порции, и в одном месте это умножение сделали бы, а в
/// другом забыли.
///
/// ПОЧЕМУ ОТДЕЛЬНО ОТ ККАЛ. Калорийность у еды уже есть в
/// <c>ConsumableProfile.Kilocalories</c>, и рядом с ней лежат вода и масса. БЖУ
/// приходит из тех же справочных таблиц, но живёт отдельной записью: у
/// несъедобных предметов БЖУ нет вовсе, а калорийность есть у еды, и смешивать
/// две разные полноты в одной структуре значило бы держать половину полей
/// пустыми и гадать, что означает ноль.
/// </summary>
public readonly record struct Macronutrients(
    double ProteinGrams,
    double FatGrams,
    double CarbohydrateGrams)
{
    /// <summary>БЖУ нет — так отвечает каталог о предмете, который не едят.</summary>
    public static Macronutrients None => default;

    /// <summary>Есть ли хоть что-то из БЖУ.</summary>
    public bool HasAny =>
        ProteinGrams > 0d ||
        FatGrams > 0d ||
        CarbohydrateGrams > 0d;

    /// <summary>
    /// Энергия, которую даёт БЖУ по калорийным коэффициентам Этвотера:
    /// 4 ккал/г белка, 9 ккал/г жира, 4 ккал/г углеводов.
    ///
    /// Нужна для СВЕРКИ, а не для начисления: питательность начисляется полем
    /// ккал из профиля. Расхождение этих двух чисел означает, что БЖУ и
    /// калорийность взяты из разных источников, и это надо видеть.
    /// </summary>
    public double EnergyKilocalories =>
        ProteinGrams * 4d +
        FatGrams * 9d +
        CarbohydrateGrams * 4d;
}
