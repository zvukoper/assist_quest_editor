namespace AssistQuestEditor.Domain;

/// <summary>
/// КАЧЕСТВО ИЗГОТОВЛЕНИЯ предмета (задано автором как ЗАДЕЛ под будущие
/// механики: крафт, износ, ремонт).
///
/// Сейчас значение у ВСЕХ предметов — <see cref="Common"/> («Обычное»). Оно
/// хранится у определения предмета как ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ: экземпляр,
/// который игрок получит из квеста или купит, начнёт жизнь с этого качества.
/// Без умолчания будущая механика крафта не знала бы, с чего начинать.
///
/// Порядок важен: он задаёт «лучше/хуже» сравнением, поэтому сортировка и
/// правила вроде «не хуже обычного» не потребуют отдельной таблицы весов.
/// </summary>
public enum ItemQuality
{
    /// <summary>Самодельное, кустарное: работает, но хуже обычного.</summary>
    Crude = 0,

    /// <summary>Обычное — значение по умолчанию для ВСЕХ предметов.</summary>
    Common = 1,

    /// <summary>Хорошее: аккуратная работа.</summary>
    Good = 2,

    /// <summary>Отличное: лучшее, что можно сделать руками.</summary>
    Excellent = 3,

    /// <summary>Легендарное: уникальные вещи из наград (например «легендарный шашлык»).</summary>
    Legendary = 4
}

/// <summary>
/// СОСТОЯНИЕ предмета (задано автором как задел под будущие механики: порча
/// еды, износ вещей, ремонт).
///
/// Умолчание зависит от того, ЕДЯТ предмет или нет: у еды «Свежее», у прочего
/// «Без повреждений». Это разные шкалы по смыслу («свежесть» нельзя применить к
/// мылу), поэтому значение по умолчанию выбирается по признаку съедобности, а не
/// одно на всех (см. <see cref="ItemAttributes.ForItem"/>).
/// </summary>
public enum ItemCondition
{
    // ── Еда и питьё ──────────────────────────────────────────────────────────
    /// <summary>Испорченное: есть опасно.</summary>
    Spoiled = 0,

    /// <summary>Просроченное: ещё съедобно, но хуже.</summary>
    Stale = 1,

    /// <summary>Свежее — значение по умолчанию для ВСЕГО съедобного.</summary>
    Fresh = 2,

    // ── Прочие предметы ──────────────────────────────────────────────────────
    /// <summary>Сломано: не работает, пока не починят.</summary>
    Broken = 3,

    /// <summary>Повреждено: работает, но хуже.</summary>
    Damaged = 4,

    /// <summary>Без повреждений — значение по умолчанию для всего несъедобного.</summary>
    Intact = 5
}

/// <summary>
/// Русские подписи для качества и состояния.
///
/// Подписи живут В ДОМЕНЕ, а не в разметке: их читают и окно предметов, и
/// журнал, и будущие правила крафта. Продублированная в JavaScript строка
/// разошлась бы с доменом при первой же правке, и игрок увидел бы одно, а
/// движок применил другое (та же причина, по которой в домене лежит цвет
/// предмета).
/// </summary>
public static class ItemAttributeLabels
{
    public static string Quality(ItemQuality quality) =>
        quality switch
        {
            ItemQuality.Crude => "Кустарное",
            ItemQuality.Good => "Хорошее",
            ItemQuality.Excellent => "Отличное",
            ItemQuality.Legendary => "Легендарное",
            _ => "Обычное"
        };

    public static string Condition(ItemCondition condition) =>
        condition switch
        {
            ItemCondition.Spoiled => "Испорченное",
            ItemCondition.Stale => "Просроченное",
            ItemCondition.Fresh => "Свежее",
            ItemCondition.Broken => "Сломано",
            ItemCondition.Damaged => "Повреждено",
            _ => "Без повреждений"
        };
}
