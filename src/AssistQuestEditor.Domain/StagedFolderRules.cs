namespace AssistQuestEditor.Domain;

/// <summary>
/// Правила переноса ПОДГОТОВЛЕННОЙ папки на её постоянное место.
///
/// Зачем отдельный контракт. Импорт распаковывает ресурс во временную папку и
/// только потом ставит его на место: прерванный импорт не должен оставлять
/// полураспакованный ресурс, который выглядит рабочим. Перенос делался одним
/// приёмом — <c>Directory.Move</c>, — и это работало до тех пор, пока временная
/// папка и каталог миров лежали на ОДНОМ томе. На обычной машине это условие
/// ложно: <c>Path.GetTempPath()</c> — это системный диск (<c>C:</c>), а
/// пользовательские данные приложения лежат в Документах, которые часто
/// перенесены на другой диск (<c>E:</c>, <c>D:</c>). Тогда ЛЮБОЙ импорт падал
/// целиком: «Пропустить» в окне первого мира и импорт кампании из меню
/// заканчивались ошибкой «Move will not work across volumes».
///
/// Переименование внутри тома — мгновенная и атомарная операция, поэтому она
/// остаётся предпочтительной. Копирование — обходной путь: он медленнее и не
/// атомарен, но он единственный, который вообще работает между томами.
///
/// Правила живут в Domain, а не в слое файлового доступа, ровно по той же
/// причине, что и раскладка путей: это проверяемое условие о ПУТЯХ, и его нужно
/// покрывать тестами, не поднимая файловую систему. Разные тома на машине
/// разработчика воспроизвести нельзя — а именно так дефект и дожил до релиза.
/// </summary>
public static class StagedFolderRules
{
    /// <summary>
    /// Можно ли поставить папку на место ПЕРЕИМЕНОВАНИЕМ.
    ///
    /// Переименование возможно только внутри одного тома; между томами оно
    /// невозможно принципиально, а не «иногда не работает». Сравнивается корень
    /// пути, а не буква диска: сравнение букв путало бы два пути с разными
    /// томами, обозначенными одним корнем (смонтированный диск, subst, UNC).
    ///
    /// Пустые и некорректные пути дают <c>false</c>: вызывающий код обязан
    /// отступить к копированию, а не падать. Решение «отступить» безопаснее
    /// решения «попробовать и узнать»: ошибка переименования уже после частичной
    /// работы оставила бы ресурс в промежуточном состоянии.
    /// </summary>
    public static bool CanRenameIntoPlace(string sourceFolder, string targetFolder)
    {
        if (string.IsNullOrWhiteSpace(sourceFolder) || string.IsNullOrWhiteSpace(targetFolder))
            return false;

        try
        {
            var sourceRoot = Path.GetPathRoot(Path.GetFullPath(sourceFolder));
            var targetRoot = Path.GetPathRoot(Path.GetFullPath(targetFolder));

            if (string.IsNullOrEmpty(sourceRoot) || string.IsNullOrEmpty(targetRoot))
                return false;

            return sourceRoot.Equals(targetRoot, StringComparison.OrdinalIgnoreCase);
        }
        catch (Exception)
        {
            // Некорректный путь (недопустимые символы, слишком длинный) — это не
            // повод падать в проверке: решение принимает вызывающий код.
            return false;
        }
    }

    /// <summary>
    /// Порядок обхода при КОПИРОВАНИИ: сначала обычные файлы, и лишь затем —
    /// файл-определитель ресурса.
    ///
    /// Это не украшение, а замена атомарности, которую даёт переименование.
    /// Каталог миров рекурсивно обходит папки и считает миром любую, внутри
    /// которой нашёлся <c>world.aqworld</c>. При копировании файлы появляются на
    /// месте по одному, поэтому определитель, скопированный первым, показывал бы
    /// миру ещё не скопированное содержимое: пользователь видел бы мир без
    /// кампаний, а каталог «находил» бы ресурс, которого ещё нет.
    ///
    /// Копия кладётся во временную папку ТОГО ЖЕ тома, что и место установки,
    /// поэтому последнее действие — переименование, то есть перемещение
    /// определителя и всей папки на место становится атомарным.
    /// </summary>
    public static IReadOnlyList<string> OrderForCopy(
        IEnumerable<string> relativePaths,
        string definingFileName)
    {
        ArgumentNullException.ThrowIfNull(relativePaths);
        ArgumentException.ThrowIfNullOrWhiteSpace(definingFileName);

        var all = relativePaths.ToArray();
        var defining = all
            .Where(path => string.Equals(
                Path.GetFileName(path), definingFileName, StringComparison.OrdinalIgnoreCase))
            .ToArray();

        var rest = all.Except(defining, StringComparer.OrdinalIgnoreCase).ToArray();

        return rest.Concat(defining).ToArray();
    }
}
