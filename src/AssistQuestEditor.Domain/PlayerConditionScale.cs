namespace AssistQuestEditor.Domain;

/// <summary>
/// Шкала состояния персонажа: проценты для показа, единицы для хранения.
///
/// СНАРУЖИ (в интерфейсе) каждая шкала показывается в процентах, ВНУТРИ —
/// измеряется единицами 0..10000. Разделение нужно потому, что процент слишком
/// груб: одна сотая шкалы равна 100 внутренним единицам, поэтому начисление «за
/// игровую минуту» при обычной игре (единицы..десятки единиц) в процентах
/// округлялось бы до нуля, и подсказка «скорость изменения» всегда показывала бы
/// 0. Внутреннее значение обязано быть ЦЕЛЫМ и ровно кратным 100, тогда процент
/// всегда получается точным целым числом и наоборот.
///
/// Переводятся только ГРАНИЦЫ. Движок состояний (усталость, стресс,
/// кумулятивные значения) считает свои пороги в процентах — так запись
/// «усталость 80% критична» и «100% за 18 часов» остаётся читаемой, — а
/// хранение, сохранения и интерфейс работают в единицах.
/// </summary>
public static class PlayerConditionScale
{
    /// <summary>Верхняя граница любой шкалы состояния.</summary>
    public const double Maximum = 10000d;

    /// <summary>Единиц в одном проценте.</summary>
    public const double UnitsPerPercent = Maximum / 100d;

    /// <summary>Единицы → проценты (0..100).</summary>
    public static double ToPercent(double units) =>
        double.IsFinite(units)
            ? Math.Clamp(units, 0d, Maximum) / UnitsPerPercent
            : 0d;

    /// <summary>
    /// Проценты → единицы (0..10000).
    ///
    /// Результат округляется до целого: шкала целочисленная, иначе накопление
    /// дробных единиц превратило бы показ процентов в «99.99%» вместо «100%».
    /// </summary>
    public static double FromPercent(double percent) =>
        double.IsFinite(percent)
            ? Math.Round(Math.Clamp(percent, 0d, 100d) * UnitsPerPercent)
            : 0d;

    /// <summary>
    /// Проценты → единицы БЕЗ округления и без ограничения знака.
    ///
    /// Для скоростей изменения: усталость при отдыхе убывает (скорость
    /// отрицательная), а медленный рост стресса на 0.02% в минуту дал бы при
    /// округлении ноль — то есть ровно то, ради чего шкала и увеличена.
    /// </summary>
    public static double RateFromPercent(double percentPerMinute) =>
        double.IsFinite(percentPerMinute) ? percentPerMinute * UnitsPerPercent : 0d;
}
