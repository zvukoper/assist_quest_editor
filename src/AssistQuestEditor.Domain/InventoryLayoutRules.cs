namespace AssistQuestEditor.Domain;

/// <summary>
/// Размеры окна инвентаря, посчитанные от сетки.
///
/// Живут в домене, а не в окне, потому что тот же расчёт нужен странице: CSS
/// задаёт сторону ячейки и отступы, окно WinForms задаёт размер. Разойдись они —
/// и содержимое либо не влезет (появится полоса прокрутки там, где сетка
/// рассчитана на весь размер), либо останется пустая полоса.
///
/// Чистая арифметика без System.Drawing: тестируется без Windows и без WinForms.
/// </summary>
public static class InventoryLayoutRules
{
    /// <summary>Столбцов в сетке инвентаря.</summary>
    public const int Columns = 6;

    /// <summary>Строк в сетке инвентаря.</summary>
    public const int Rows = 3;

    /// <summary>Всего ячеек. Пустые рисуются намеренно: по ним видно свободное место.</summary>
    public const int Capacity = Columns * Rows;

    /// <summary>
    /// Сторона квадратной ячейки в пикселях.
    ///
    /// Прежняя ячейка была 78×78. «Вчетверо меньше» — это четверть ПЛОЩАДИ, то
    /// есть сторона вдвое меньше: 39. Уменьшение стороны вчетверо дало бы 19 px,
    /// где подпись предмета перестала бы читаться.
    /// Значение совпадает с <c>--inventory-cell</c> в theme.css и проверяется
    /// прогоном: разойтись они не должны.
    /// </summary>
    public const int CellSize = 39;

    /// <summary>Зазор между ячейками.</summary>
    public const int CellGap = 7;

    /// <summary>Отступ сетки от краёв панели.</summary>
    public const int GridPadding = 10;

    /// <summary>Высота заголовка панели инвентаря.</summary>
    public const int HeaderHeight = 34;

    /// <summary>
    /// Высота блока потребностей (здоровье, энергия, жидкость, усталость).
    ///
    /// Значение ИЗМЕРЕНО на отрисованной странице: четыре строки полосок плюс
    /// отступы дают ровно 79 px. Прежняя оценка «на глаз» (104) оставляла пустую
    /// полосу над кошельком ровно в 25 px — окно выглядело так, будто содержимое
    /// не догрузилось.
    /// </summary>
    public const int VitalsHeight = 79;

    /// <summary>Высота кошелька (деньги, опыт, резерв).</summary>
    public const int WalletHeight = 30;

    /// <summary>Поле окна вокруг содержимого.</summary>
    public const int WindowPadding = 2;

    /// <summary>
    /// Ширина КЛИЕНТСКОЙ области окна: измерена по образцу, заданному автором.
    ///
    /// Шесть столбцов по 39 px плюс зазоры и отступы дают 289 — в образце окно
    /// шире, потому что сетка в нём выровнена по центру и по бокам остаётся
    /// свободное место. Берётся ровно образец, а не «сколько нужно сетке»:
    /// иначе окно было бы уже и выглядело сжатым.
    /// </summary>
    public const int ClientWidth = 800;

    /// <summary>
    /// Высота КЛИЕНТСКОЙ области окна из образца: три строки сетки.
    ///
    /// Число строк в окне БОЛЬШЕ ТРЁХ не увеличивает высоту по умолчанию: окно
    /// открывается такого размера, и если предметов больше, чем ячеек, снизу
    /// появляется прокрутка — растягивать окно под неизвестное заранее число
    /// предметов значило бы менять размер при каждом получении предмета.
    /// </summary>
    public const int ClientHeight = 392;

    /// <summary>Ширина сетки: столбцы, зазоры между ними и отступы по краям.</summary>
    public static int GridWidth =>
        Columns * CellSize + (Columns - 1) * CellGap + GridPadding * 2;

    /// <summary>Высота сетки: строки и зазоры между ними.</summary>
    public static int GridHeight =>
        Rows * CellSize + (Rows - 1) * CellGap + GridPadding * 2;

    /// <summary>
    /// Ширина окна вместе с рамкой и полями.
    ///
    /// Клиентская ширина задана образцом, поэтому к ней добавляются только поля
    /// WinForms: рамка и заголовок занимают место СНАРУЖИ клиента, и без этой
    /// прибавки клиент оказался бы меньше образца ровно на толщину рамки.
    /// </summary>
    public static int WindowWidth => ClientWidth + WindowPadding * 2;

    /// <summary>Высота окна вместе с рамкой и заголовком.</summary>
    public static int WindowHeight => ClientHeight + WindowPadding * 2 + TitleBarAllowance;

    /// <summary>
    /// Запас на заголовок и рамку окна.
    ///
    /// В образце заголовок окна занимает 31 px, поэтому он и вычтен из общей
    /// высоты снимка. Число фиксировано: заголовок стандартного окна Windows не
    /// зависит от содержимого, а попытка вычислить его через
    /// <c>SystemInformation</c> дала бы другое значение при других настройках
    /// оформления, и окно «прыгало» бы между машинами.
    /// </summary>
    public const int TitleBarAllowance = 31;

    /// <summary>
    /// Минимальная высота окна: одна строка сетки.
    ///
    /// Меньше одной строки окно не имеет смысла, а требовать три строки значило
    /// бы запретить уменьшать окно, хотя прокрутка это уже позволяет.
    /// </summary>
    public static int MinimumWindowHeight =>
        HeaderHeight + VitalsHeight + SingleRowGridHeight + WalletHeight +
        WindowPadding * 2 + TitleBarAllowance;

    /// <summary>Высота сетки в одну строку.</summary>
    private static int SingleRowGridHeight => CellSize + GridPadding * 2;
}
