    /// <summary>
    /// Средняя розничная цена предмета в рублях. Ноль — «не продаётся».
    ///
    /// Ноль стоит у КВЕСТОВЫХ предметов (мясо Руслана, записка) и у того, что
    /// покупается не за деньги (сигареты выдают, мазь выдаёт медик). Цена у них
    /// означала бы обещание покупки, которого нет.
    /// </summary>
    public static int PriceRubles(string itemId) =>
        Prices.TryGetValue(
            itemId ?? string.Empty,
            out var price)
                ? price
                : 0;

    /// <summary>БЖУ порции. Пусто — предмет не едят.</summary>
    public static Macronutrients Nutrition(string itemId) =>
        NutritionByItem.TryGetValue(
            itemId ?? string.Empty,
            out var value)
                ? value
                : Macronutrients.None;

