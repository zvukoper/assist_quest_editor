    /// ЗАДЕЛ: у всех предметов качество «Обычное», а состояние зависит от того,
    /// едят предмет или нет, — «Свежее» у еды и «Без повреждений» у прочего.
    /// Отдельной таблицы НЕТ намеренно: автор задал именно УМОЛЧАНИЯ, а таблица
    /// из восьмидесяти одинаковых строк приглашала бы завести восемьдесят разных
    /// значений до того, как появятся механики, которые их меняют.
    /// </summary>
    public static (ItemQuality Quality, ItemCondition Condition) Attributes(
        string itemId,
        bool edible) =>
        (
            ItemQuality.Common,
            edible
                ? ItemCondition.Fresh
                : ItemCondition.Intact
        );

