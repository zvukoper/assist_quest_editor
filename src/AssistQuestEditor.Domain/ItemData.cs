/// <summary>
/// Справочные данные предметов, которых НЕ было в каталоге до этой правки:
/// БЖУ, цены и атрибуты экземпляра.
///
/// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. <see cref="CharacterConsumableCatalog"/> описывает, ЧТО
/// предмет начисляет шкалам (ккал, вода, вес порции). Здесь лежит то, что на шкалы
/// сейчас НЕ влияет, но понадобится механикам: состав еды, цена и качество с
/// состоянием. Смешав их, мы получили бы файл, где правка цены соседствует с
/// правкой баланса, и ревью баланса тонуло бы в ценах.
///
/// ИСТОЧНИКИ ЧИСЕЛ (заданы автором).
///   • БЖУ и калорийность еды — таблицы калорийности «Крупы и каши», «Молочные
///     продукты», «Фрукты», «Овощи и зелень», «Соки и компоты», «Первые блюда»,
///     «Салаты», «Бутерброды» (calorizator) и карточки состава блюд (health-diet).
///     Справочники публикуют данные НА 100 Г, а игрок ест ПОРЦИЮ, поэтому в
///     каталоге БЖУ пересчитано на массу порции — один раз и здесь.
///   • Цены кафе — из плана «Кафе „У Дороги“» (автор). Это единственные цены,
///     которые автор задал лично, и подменять их «средними по рынку» нельзя.
///   • Цены остальных предметов — средние по открытым источникам розницы
///     (сетевые магазины и маркетплейсы), округлены до рубля. Это ОЦЕНКА
///     порядка величины, а не прайс конкретной сети: автор просил «найти в
///     интернете или вычислить по открытым источникам», поэтому числа выведены
///     из розничных диапазонов, а не выбраны произвольно. Квестовые предметы
///     цены не имеют вовсе: они не продаются никогда, и цена у них означала бы
///     возможность покупки.
/// </summary>
public static class ItemData
