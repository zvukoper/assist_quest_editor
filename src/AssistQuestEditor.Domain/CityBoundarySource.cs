namespace AssistQuestEditor.Domain;

/// <summary>
/// Источник черт городов, который можно перечитать.
///
/// Зачем отдельная абстракция, а не просто <see cref="CityBoundaryIndex"/>:
/// черты рисует автор ВРУЧНУЮ и в отдельном окне, а индекс критериев читается
/// один раз при старте. Передай мы индекс напрямую — автор нарисовал бы черту,
/// нажал «Проверить» в уже открытом окне панели локаций и всё равно получил бы
/// «ни одна черта города не нарисована»: окно держит снимок, сделанный до
/// рисования. Симптом при этом выглядит как поломка геометрии, а причина — в
/// устаревшем снимке, поэтому обновление обязано быть частью типа, а не
/// договорённостью между вызывающими.
/// </summary>
public interface ICityBoundarySource
{
    /// <summary>Актуальные черты. Реализация решает, читать ли файл заново.</summary>
    CityBoundaryIndex Current { get; }
}

/// <summary>
/// Неизменяемый снимок черт.
///
/// Нужен там, где обновление не требуется или невозможно: тесты, запуск без
/// пользовательских данных, окно рисования (оно и есть источник изменений и
/// перечитывает файл само).
/// </summary>
public sealed class StaticCityBoundarySource(CityBoundaryIndex? boundaries = null) : ICityBoundarySource
{
    public CityBoundaryIndex Current { get; } = boundaries ?? CityBoundaryIndex.Empty;
}
