namespace AssistQuestEditor.Domain;

/// <summary>
/// Пользовательская правка списка перекрёстков: что исключить и что добавить.
///
/// Зачем нужна ручная правка, если есть автоматический поиск: алгоритм находит
/// перекрёстки по геометрии и не видит уровней. Мост или эстакада пересекаются в
/// плане, но повернуть там нельзя — такие узлы надо исключать. И наоборот,
/// примыкание, которое в данных нарисовано с большим разрывом, поиск пропустит —
/// его надо добавить руками. Крупные развязки, кольца и логистические площадки
/// автор тоже вычищает вручную: на кольцах и развязках запрещена остановка, а у
/// площадок слишком густая сеть дорог — для квестов они не годятся.
///
/// Живёт в домене, а не в App, потому что здесь ПРАВИЛО (что считать исключённым
/// и что добавленным, и кто из них важнее), а не работа с файлом. Правило
/// проверяется тестами домена; запись и чтение файла остаются в App.
///
/// Именно координаты, а не индексы в автоматическом списке: индексы сломались бы
/// при любом пересчёте автоматического списка (другой допуск сшивки — и все правки
/// указали бы не туда). Координата переживает пересчёт, а совпадение ищется с
/// допуском.
/// </summary>
public sealed record JunctionReview(
    IReadOnlyList<JunctionPoint> Excluded,
    IReadOnlyList<JunctionPoint> Added)
{
    public static JunctionReview Empty { get; } =
        new(Array.Empty<JunctionPoint>(), Array.Empty<JunctionPoint>());

    /// <summary>
    /// Радиус, в пределах которого правка считается относящейся к перекрёстку.
    ///
    /// Не ноль: координаты округляются до сантиметра при записи, а автоматический
    /// список может быть пересчитан с другой точностью. Полметра заведомо больше
    /// этого расхождения и заведомо меньше расстояния между разными перекрёстками
    /// (в городе они стоят не ближе ~40 м).
    /// </summary>
    public const double MatchRadius = 0.5;

    public bool IsExcluded(JunctionPoint junction) =>
        Excluded.Any(point => Distance(point, junction) <= MatchRadius);

    public bool IsAdded(JunctionPoint junction) =>
        Added.Any(point => Distance(point, junction) <= MatchRadius);

    /// <summary>
    /// Итоговый список перекрёстков: автоматические минус исключённые плюс
    /// добавленные.
    ///
    /// Порядок сохраняется: исключённые выпадают со своих мест, добавленные
    /// дописываются в конец. Это важно для навигации «следующий/предыдущий» —
    /// автор видит тот же порядок, что и при поиске.
    ///
    /// ДОБАВЛЕННЫЙ узел имеет ПРИОРИТЕТ над исключением рядом с ним.
    ///
    /// Это не украшение, а необходимое правило для типичной работы автора: он
    /// вычищает кольцо целиком (десятки серых точек), а потом вручную ставит ОДИН
    /// зелёный перекрёсток поверх вычищенного места — на трассе у кольца, где
    /// остановка разрешена и узел для квеста подходит. Если бы исключение
    /// побеждало, этот узел попадал бы в список вычитания и пропадал бы из
    /// поиска, хотя автор только что поставил его сознательно.
    ///
    /// Поэтому исключение применяется ТОЛЬКО к автоматическим узлам и никогда к
    /// добавленным: «исключить» — это «не верю автоматике здесь», а не «запрещаю
    /// этому месту быть перекрёстком».
    ///
    /// Сравнение идёт по МЕСТУ (координатам), а не по происхождению узла, поэтому
    /// порядок проверок задаёт приоритет, и его нельзя переставлять.
    /// </summary>
    public IReadOnlyList<JunctionPoint> Apply(IReadOnlyList<JunctionPoint> detected)
    {
        var result = new List<JunctionPoint>(detected.Count + Added.Count);

        foreach (var junction in detected)
        {
            // Исключение действует ТОЛЬКО на автоматику: узел, который автор
            // подтвердил вручную, остаётся в списке, даже если его место помечено
            // исключённым. Узел при этом сохраняет СВОЁ место в порядке списка —
            // иначе навигация «следующий/предыдущий» перескакивала бы, хотя автор
            // всего лишь подтвердил узел там, где он и был.
            if (IsExcluded(junction) && !IsAdded(junction))
                continue;

            result.Add(junction);
        }

        foreach (var junction in Added)
        {
            // Добавленный узел может совпасть с уже принятым найденным (в том
            // числе с подтверждённым выше) — тогда дубликат не нужен.
            if (result.Any(item => Distance(item, junction) <= MatchRadius))
                continue;

            result.Add(junction);
        }

        return result;
    }

    private static double Distance(JunctionPoint a, JunctionPoint b)
    {
        var dx = a.X - b.X;
        var dz = a.Z - b.Z;
        return Math.Sqrt(dx * dx + dz * dz);
    }
}
