namespace AssistQuestEditor.Domain;

/// <summary>
/// Тематическое изображение мира или кампании — квадрат, и правило приведения
/// к квадрату живёт здесь.
///
/// В домене, а не в окне: обрезка нужна в ДВУХ местах (окно свойств при выборе
/// файла и любая будущая пакетная обработка), и две реализации расходились бы.
/// Плюс это чистая арифметика: её можно покрыть тестами без WinForms и без
/// System.Drawing, который есть только на Windows.
///
/// Квадрат — не косметика: изображение показывается эскизом в списках, и
/// необъединённые пропорции давали «пляшущие» рамки: одна картинка вытянута
/// вверх, другая вбок, третья мелкая в центре.
/// </summary>
public static class ImageCropRules
{
    /// <summary>
    /// Квадрат, вырезаемый из изображения: сторона и смещение.
    /// </summary>
    /// <param name="X">Смещение по горизонтали до левого края квадрата.</param>
    /// <param name="Y">Смещение по вертикали до верхнего края квадрата.</param>
    /// <param name="Side">Сторона квадрата.</param>
    /// <param name="SourceWidth">Ширина исходного изображения.</param>
    /// <param name="SourceHeight">Высота исходного изображения.</param>
    public readonly record struct SquareCrop(
        int X,
        int Y,
        int Side,
        int SourceWidth,
        int SourceHeight)
    {
        /// <summary>
        /// Квадрат совпадает с исходником: обрезать нечего.
        ///
        /// Тогда изображение сохраняется как есть — повторное кодирование
        /// только потеряло бы качество, ничего не улучшив.
        /// </summary>
        public bool IsNoOp => SourceWidth == Side && SourceHeight == Side;
    }

    /// <summary>
    /// Считает квадрат по центру изображения.
    ///
    /// Сторона — МЕНЬШАЯ из сторон. Так изображение никогда не обрезается по
    /// большей стороне до нуля и не растягивается: вписанный квадрат — это
    /// единственный вариант, при котором не теряется содержимое целиком.
    /// Для вытянутого вбок снимка это означает обрезку по бокам, для снимка
    /// вверх — обрезку сверху и снизу.
    ///
    /// Выравнивание по центру, а не по верхнему краю: у снимков мира и портретов
    /// значимое обычно в середине кадра, а отрезание сверху срезало бы именно
    /// сюжет.
    /// </summary>
    /// <exception cref="ArgumentOutOfRangeException">
    /// Для неположительных размеров: изображение нулевой ширины или высоты —
    /// это повреждённый файл, и молча вернуть пустой квадрат означало бы
    /// записать в ресурс пустую картинку.
    /// </exception>
    public static SquareCrop CenteredSquare(int width, int height)
    {
        if (width <= 0)
            throw new ArgumentOutOfRangeException(nameof(width), width,
                "Ширина изображения должна быть положительной.");
        if (height <= 0)
            throw new ArgumentOutOfRangeException(nameof(height), height,
                "Высота изображения должна быть положительной.");

        var side = Math.Min(width, height);
        var x = (width - side) / 2;
        var y = (height - side) / 2;

        return new SquareCrop(x, y, side, width, height);
    }
}
