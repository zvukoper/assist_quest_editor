namespace AssistQuestEditor.Domain;

/// <summary>
/// Авторство ресурса, когда псевдоним НЕ указан.
///
/// Умолчание «подставь имя машины» уже было: приложение подписывало ресурсы
/// синтетическим <c>User_ГГММДДЧЧмм</c>, и в файле появлялась подпись, которой
/// человек не выбирал. Это хуже пропуска: подпись выглядит как настоящая, по ней
/// нельзя ни найти автора, ни понять, что он имя не задавал.
///
/// Поэтому «имени нет» — это ОТДЕЛЬНОЕ состояние с собственным словом, а не
/// отсутствие значения. Слово пишется в created_by/modified_by как обычный
/// псевдоним, поэтому формат ресурсов не меняется и старые версии читают файл
/// без правок. Оно намеренно не похоже на псевдоним: по нему сразу видно, что
/// авторство не указано.
///
/// «Анонимно» (с одной «н») — слово из требования автора. Оно проходит правило
/// <see cref="ResourceMetadata.IsValidAuthor"/>: буквы кириллицы разрешены.
/// </summary>
public static class AuthorIdentity
{
    /// <summary>Подпись, которой заменяется псевдоним, когда его нет.</summary>
    public const string Anonymous = "анонимно";

    /// <summary>
    /// Приводит псевдоним к тому, что попадёт в файл.
    ///
    /// Пустое значение и пробелы — это «не указано», а не ошибка: вызывающий код
    /// не должен решать, чем заменить пустоту, иначе правило размножится по
    /// сторам и разойдётся.
    /// </summary>
    public static string Resolve(string? author) =>
        string.IsNullOrWhiteSpace(author) ? Anonymous : author.Trim();

    /// <summary>
    /// Указан ли псевдоним человеком. Ложь и для пустоты, и для
    /// <see cref="Anonymous"/>: сохранённая подпись «анонимно» означает ровно то
    /// же, что пустое поле в настройках, — иначе приложение считало бы, что имя
    /// указано, и перестало бы его спрашивать.
    /// </summary>
    public static bool IsNamed(string? author) =>
        !string.IsNullOrWhiteSpace(author) &&
        !string.Equals(author.Trim(), Anonymous, StringComparison.OrdinalIgnoreCase);
}
