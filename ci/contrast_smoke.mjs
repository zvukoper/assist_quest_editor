// Читаемость текста в тёмных диалогах.
//
// Проверка ЗАМЕРЯЮЩАЯ и поведенческая. Дефект, который она стережёт, в исходниках
// невидим: цвета заданы верно (`ForeColor` светлый, `BackColor` тёмный), но у
// ВЫКЛЮЧЕННОЙ кнопки WinForms рисует текст СИСТЕМНЫМ серым, игнорируя заданный
// цвет. На светлой теме это бледный серый, на тёмном фоне диалога — тёмно-серый.
// Замерено на настоящем экране: яркость текста 65 при фоне 24, контраст 2,1:1 —
// вдвое ниже минимума 4,5:1, то есть панель «Выбрать изображение…» в окне
// сведений не читалась вовсе.
//
// Мерить приходится ОТРИСОВАННОЕ окно: `DrawToBitmap` отдаёт то, что просит код,
// а не то, что рисует система. Проба `--contrast-probe` сама показывает диалоги и
// считает контраст; здесь проверяется и наличие обходного пути, и его РАБОТА:
// статическая проверка класса без запуска прошла бы на классе, который никто не
// использует.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = process.cwd();
const read = rel => fs.readFileSync(path.join(root, ...rel.split("/")), "utf8");

const failures = [];
const check = (condition, message) => { if (!condition) failures.push(message); };

const button = read("src/AssistQuestEditor.App/Host/DarkFlatButton.cs");
const program = read("src/AssistQuestEditor.App/Program.cs");

// --- 1. Класс кнопки: выключенное состояние рисуется сам ---

check(/class DarkFlatButton : Button/.test(button),
  "Кнопка с читаемым выключенным состоянием должна быть отдельным классом кнопки.");
check(/protected override void OnPaint\(PaintEventArgs e\)/.test(button),
  "Без своей отрисовки выключенный текст остаётся системно-серым: перекрыть его свойством нельзя.");
// Ветка «включена — отдать базовому классу» обязательна: если рисовать обе ветки
// вручную, потеряется оформление темы у рабочей кнопки.
check(/if \(Enabled\)[\s\S]{0,80}?base\.OnPaint\(e\);[\s\S]{0,40}?return;/.test(button),
  "Включённая кнопка должна рисоваться базовым классом: иначе пропадёт оформление темы.");
check(/TextRenderer\.DrawText\(/.test(button) && /DisabledTextColor/.test(button),
  "Выключенный текст должен рисоваться СВОИМ цветом, а не системным.");
// Свойство цвета обязано быть скрыто от конструктора форм: проект собирается с
// TreatWarningsAsErrors, и WFO1000 валит сборку.
check(/\[DesignerSerializationVisibility\(DesignerSerializationVisibility\.Hidden\)\]/.test(button),
  "Свойство цвета выключенного текста обязано быть помечено атрибутом: иначе сборка падает на WFO1000.");

// Цвет читается (5,2:1 на фоне 23,24,25) и при этом заметно приглушён.
const disabledColor = /169, 178, 190|170, 178, 190/.test(button);
check(disabledColor,
  "Цвет выключенного текста должен быть светлым: он обязан давать контраст выше 4,5:1.");

// Акцентная (оранжевая) кнопка. Тот же приглушённый серый на ней даёт «серое на
// жёлтом» — ровно тот дефект, который автор увидел: текст почти не читается.
// Цвет обязан выбираться ПО ФОНУ: на тёмной кнопке серый верен, на оранжевой
// нужен тёмный.
check(/DisabledTextFor\(/.test(button),
  "Цвет выключенного текста обязан зависеть от фона кнопки: серый на акценте не читается.");
check(/Luma\(background\) > LightBackgroundLuma/.test(button),
  "Порог «светлый фон» обязателен: без него акцентная кнопка остаётся «серой на жёлтом».");
check(/Color\.FromArgb\(20, 20, 20\)/.test(button),
  "На светлом фоне выключенный текст обязан быть тёмным: только он даёт контраст выше 4,5:1.");

// --- 2. Диалоги действительно используют этот класс ---

const dialogs = [
  ["ResourcePropertiesForm.cs", "окно сведений и правки ресурса"],
  ["ResourceExportForm.cs", "диалог экспорта"],
  ["ArchiveImportForm.cs", "диалог импорта архива"],
  ["ImportParentForm.cs", "выбор родителя при импорте"],
  ["ResourceCreateForm.cs", "создание ресурса"],
  ["WorldChooserForm.cs", "выбор мира"],
  ["SettingsForm.cs", "настройки"],
  ["FirstRunSetupForm.cs", "первичная настройка"]
];

for (const [file, label] of dialogs) {
  const source = read("src/AssistQuestEditor.App/Host/" + file);
  check(/DarkFlatButton/.test(source),
    `${label}: кнопки должны использовать класс с читаемым выключенным состоянием (${file}).`);
  // Обычных плоских кнопок остаться не должно: одна забытая — и именно она
  // окажется той, что выключается.
  check(!/FlatStyle = FlatStyle\.Flat/.test(source),
    `${label}: остались обычные плоские кнопки — у них выключенный текст системно-серый (${file}).`);
}

// --- 2а. Каждая заливка акцентом обязана иметь ТЁМНЫЙ текст ---
//
// Проверка ОБЩАЯ, а не по списку диалогов выше: список пришлось бы дополнять при
// каждой новой оранжевой кнопке, и первая же забытая осталась бы непроверенной —
// а именно на ней дефект и появился бы. Здесь сканируются ВСЕ диалоги хост-слоя,
// поэтому новая акцентная кнопка попадает под проверку сама.
//
// Порог суммы каналов выбран с запасом: измеренный тёмный текст — (20,20,20) и
// (28,28,28), то есть 60-84; приглушённый серый (170,178,190) даёт 538.
for (const file of fs.readdirSync(path.join(root, "src", "AssistQuestEditor.App", "Host"))) {
  if (!file.endsWith(".cs")) continue;
  const source = read("src/AssistQuestEditor.App/Host/" + file);
  const accentFill = /BackColor\s*=\s*Color\.FromArgb\(250,\s*176,\s*3\)/g;
  let match;
  while ((match = accentFill.exec(source)) !== null) {
    // Окно УЗКОЕ и берётся В ОБЕ стороны, но проверяется только СЛЕДУЮЩИЙ цвет
    // текста. Широкое окно ловит `ForeColor` соседнего контрола: в этих диалогах
    // поля ввода задают светлый цвет, и проверка падала бы на них, а не на кнопке.
    // В акцентной кнопке пары свойств идут подряд (замерено: `BackColor` и
    // `ForeColor` на соседних строках), а между кнопками дистанция больше окна.
    const after = source.slice(match.index, match.index + 200);
    const fore = /ForeColor\s*=\s*Color\.FromArgb\((\d+),\s*(\d+),\s*(\d+)\)/.exec(after);
    check(fore !== null,
      `${file}: заливка акцентом без своего цвета текста — WinForms возьмёт системный серый.`);
    if (fore !== null) {
      const sum = Number(fore[1]) + Number(fore[2]) + Number(fore[3]);
      check(sum < 200,
        `${file}: на акцентной заливке светлый текст (${fore[1]},${fore[2]},${fore[3]}) — ` +
        "это «серое на жёлтом», тот самый нечитаемый вид.");
    }
  }
}

// --- 2б. Акцентные (оранжевые) поверхности в веб-интерфейсе ---
//
// Дефект «серое на жёлтом» в CSS не видно по цветам: они заданы верно, но
// ВЫКЛЮЧЕННЫЙ элемент приглушается прозрачностью, а прозрачность смешивает
// оранжевый ФОН с тёмной панелью и роняет контраст. Замерено в браузере:
// `button.primary:disabled` с приглушением прозрачностью даёт 2,7:1, а кружок с
// номером выбранного варианта — 2,8:1 (на живом оранжевом без приглушения 9,2:1).
// Отдельно проверять это нужно ещё и потому, что общее правило
// `button:disabled` ловит И акцентные кнопки, и `.interfaceChoice`.
const theme = read("src/AssistQuestEditor.App/Web/theme.css");

// Общее правило приглушения выключенных кнопок обязано существовать: без него
// выключенную кнопку вообще не отличить от рабочей.
check(/button:disabled,\.toolButton:disabled,\.navButton:disabled\{[^}]*opacity:[\d.]+[^}]*\}/.test(theme),
  "theme.css должен приглушать выключенные кнопки — иначе их не отличить от рабочих.");

// Выключенная акцентная кнопка. Требуется ОБА условия: приглушение фоном (а не
// прозрачностью) и снятая прозрачность. Одного фона мало: `opacity:.45` из общего
// правила продолжает приглушать и ТЕКСТ, и контраст падает вместе с ним.
const disabledPrimary = /button\.primary:disabled,\.toolButton\.primary:disabled\{[\s\S]*?\n\}/.exec(theme)?.[0] ?? "";
check(disabledPrimary.length > 0,
  "theme.css обязан отдельно задавать вид ВЫКЛЮЧЕННОЙ акцентной кнопки: " +
  "общее приглушение прозрачностью делает её нечитаемой.");
check(/opacity:\s*1/.test(disabledPrimary),
  "У выключенной акцентной кнопки прозрачность обязана быть снята: " +
  "иначе приглушается и текст, и контраст падает вместе с фоном.");
check(/linear-gradient\(\s*rgba\(11,13,17,\.\d+\)/.test(disabledPrimary),
  "Выключенная акцентная кнопка обязана приглушаться ЗАЛИВКОЙ поверх акцента, " +
  "а не прозрачностью: у оранжевого яркость у порога, и приглушение прозрачностью даёт 2,7:1.");

// Кружок с номером варианта: фон — акцент, текст тёмный, и родитель не глушит его.
check(/\.interfaceChoiceIndex\{[^}]*background:var\(--accent\)/.test(theme),
  "Кружок с номером варианта обязан быть акцентным: это заливка акцентом, а не только текст.");
check(/\.interfaceChoiceIndex\{[^}]*color:#1b1b1b/.test(theme),
  "Текст на акцентном кружке обязан быть тёмным: светлый дал бы «серое на жёлтом».");
const disabledChoice = /\.interfaceChoice:disabled\{[\s\S]*?\n\}/.exec(theme)?.[0] ?? "";
check(/opacity:\s*1/.test(disabledChoice),
  "`.interfaceChoice` — это <button>, и его ловит общее `button:disabled{opacity}`: " +
  "в выключенном состоянии прозрачность обязана сниматься, иначе выбранный вариант уходит в 2,8:1.");

// --- 3. Реальный замер отрисованных диалогов ---

const exe = findExecutable();
if (exe === null) {
  failures.push("Не найден собранный AssistQuestEditor.exe для пробы читаемости.");
} else {
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "aq-contrast-"));
  const report = path.join(workspace, "report.txt");
  const capture = path.join(workspace, "capture");

  // `--capture` ОБЯЗАТЕЛЕН, и вот почему: замер вне экрана (`DrawToBitmap`) отдаёт
  // то, что ПРОСИТ код, — то есть заданные цвета — и у системно отрисованной
  // выключенной кнопки он показывает светлый текст, которого на экране нет.
  // Именно поэтому первый прогон негативного контроля «диалог на обычной кнопке»
  // проходил с дефектом. Снимок экрана берёт РЕАЛЬНУЮ отрисовку.
  //
  // Код возврата не проверяется отдельно: проба сообщает о находке ТЕКСТОМ
  // отчёта, а execFileSync на ненулевом коде бросает исключение. Без перехвата
  // проверка падала бы стектрейсом вместо внятного «кнопка не читается», и
  // негативный контроль засчитал бы мутанта непойманным.
  try {
    execFileSync(exe, ["--contrast-probe", "--capture", capture, "--report", report],
      { stdio: "pipe", timeout: 180000 });
  } catch {
    // Результат читается из отчёта ниже.
  }

  const probe = fs.existsSync(report) ? fs.readFileSync(report, "utf8") : "";

  check(/Читаемость диалогов проверена/.test(probe),
    "Проба читаемости не отработала: " + probe);
  check(/contrast: ok/.test(probe),
    "Найдены нечитаемые контролы: " + probe);
  // Покрытие обязательно: без него удаление диалога из пробы СНИЖАЛО бы охват,
  // и проверка оставалась бы зелёной — «нет нечитаемых» верно и на пустом списке.
  check(/coverage: ok/.test(probe),
    "Проба читаемости не покрывает обязательные диалоги: " + probe);

  // Число замеров должно быть достаточным: кнопки семи диалогов плюс поля ввода.
  const measured = /buttons measured: (\d+)/.exec(probe);
  check(measured !== null && Number(measured[1]) >= 18,
    "Замерено подозрительно мало кнопок: " + (measured?.[1] ?? "нет строки") + ".");

  // Отдельно проверяется, что замер действительно нашёл текст, а не рамку:
  // контраст должен быть выше минимума у КАЖДОЙ строки.
  const ratios = [...probe.matchAll(/контраст (\d+),(\d+):1/g)].map(match =>
    Number(match[1]) + Number(match[2]) / 10);
  check(ratios.length >= 18, "Замеры контраста отсутствуют: " + probe);
  check(ratios.every(value => value >= 4.5),
    "Есть контролы с контрастом ниже 4,5:1: " + ratios.filter(value => value < 4.5).join(", "));

  // Отдельно требуется, чтобы среди замеров БЫЛА выключенная кнопка. Без этого
  // возврат к пропуску выключенных контролов снова сделал бы замер слепым к
  // дефекту, ради которого он написан, а проверка осталась бы зелёной.
  check(/\(выключена\): контраст/.test(probe),
    "Выключенные кнопки не замерены: у них системная отрисовка и именно там был дефект.");

  // Акцентные (оранжевые) поверхности. Их приходится считать отдельно: в общем
  // отчёте видна только ЯРКОСТЬ («фон 178, текст 19»), по которой не понять, что
  // поверхность оранжевая, а цвет текста на акцентной кнопке выбирается по фону.
  //
  // Счётчик обязателен по той же причине, что и `coverage`: «нет серого на
  // оранжевом» верно и тогда, когда ни одна акцентная кнопка не замерена.
  const accentLines = probe.match(/^accent: .*$/gm) ?? [];
  const accentCount = /accent surfaces measured: (\d+)/.exec(probe);
  check(accentCount !== null,
    "Проба не сообщила о числе замеренных акцентных поверхностей: " + probe);
  check(accentLines.length >= 5,
    "Замерено подозрительно мало акцентных поверхностей: " + accentLines.length +
    " — акцентные кнопки обязаны попадать в замер.");
  check(accentCount !== null && Number(accentCount[1]) === accentLines.length,
    "Счётчик акцентных поверхностей расходится с числом строк замеров: " +
    accentCount?.[1] + " против " + accentLines.length + ".");

  // Цвет текста на каждой акцентной поверхности обязан быть ТМНЫМ. Порог 90
  // берётся с запасом: измеренный тёмный текст даёт 19-27, а приглушённый серый
  // на оранжевом — 65 и выше, то есть тот самый нечитаемый вид.
  const accentTextLuma = accentLines.map(line => Number(/текст (\d+)/.exec(line)?.[1]));
  check(accentTextLuma.every(value => Number.isFinite(value) && value < 90),
    "На акцентной поверхности светлый текст — это «серое на жёлтом»: " +
    accentLines.filter((_, index) => !(accentTextLuma[index] < 90)).join("; "));

  // Хотя бы одна акцентная кнопка обязана быть ВКЛЮЧЕНА. Выключенная рисуется
  // другой ветвью кода, поэтому без включённой замерялась бы только она, и
  // цвет рабочей кнопки остался бы непроверенным.
  check(accentLines.some(line => !line.includes("(выключена)")),
    "Ни одна ВКЛЮЧЁННАЯ акцентная кнопка не замерена: рабочее состояние акцента не проверено.");

  // Перекрытие контролов. Отдельная проверка, а не часть замера контраста:
  // «кнопка под кнопкой» контрастом не измеряется вовсе. Симптом был конкретный:
  // в окне создания первого мира «Создать мир» и «Пропустить» стояли в одной
  // точке, вторая шире и добавлена позже — она закрывала первую целиком, и
  // нажать её мышью было нельзя, а Enter при этом работал.
  const overlaps = /overlaps found: (\d+)/.exec(probe);
  check(overlaps !== null, "Проба не сообщила о перекрытии контролов: " + probe);
  check(overlaps !== null && Number(overlaps[1]) === 0,
    "Кнопки налезают друг на друга: " +
    (probe.match(/^overlap: .*$/gm) ?? []).join("; "));
  check(!/^overlap: /m.test(probe),
    "В отчёте есть строки overlap — перекрытие обязано быть устранено.");
}

if (failures.length) {
  console.log("Читаемость диалогов: FAIL");
  failures.forEach(item => console.log(" - " + item));
  process.exit(1);
}

console.log("Читаемость диалогов: OK выключенные кнопки читаемы, перекрытий нет, " +
  "окна сведений, экспорта, импорта, создания, мира, настроек и первичной настройки замерены.");

function findExecutable() {
  const base = path.join(root, "src", "AssistQuestEditor.App", "bin");
  if (!fs.existsSync(base)) return null;

  // Берётся САМЫЙ СВЕЖИЙ exe: в дереве лежат сборки Debug и Release, и
  // произвольная из них оказалась бы устаревшей — проба мерила бы прежний код.
  const found = [];
  const stack = [base];
  while (stack.length) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) stack.push(full);
      else if (entry.name === "AssistQuestEditor.exe") found.push(full);
    }
  }

  return found.sort((left, right) =>
    fs.statSync(right).mtimeMs - fs.statSync(left).mtimeMs)[0] ?? null;
}
